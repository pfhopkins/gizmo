"""Convert an Athena++ 1D tab dump of the primitives into test/<name>/<name>_exact.txt.

    python3 athena_tab_to_exact.py <name> <run_dir>/<name>.block0.out1.00001.tab <athena_commit> \
        "<configure line>" "<integrator, reconstruction>"

See README.md for the full procedure.
"""

import datetime
import sys

import numpy as np

name, tab, commit, configure, scheme = sys.argv[1:6]
with open(tab) as f:
    time_line = f.readline().lstrip("#").strip()
    cols = f.readline().lstrip("#").split()
d = np.loadtxt(tab)
c = {k: d[:, i] for i, k in enumerate(cols)}
Bx = c["Bcc1"]
assert np.ptp(Bx) <= 1e-12 * abs(Bx[0]), "Bx is not constant"
out = np.column_stack([c["x1v"], c["rho"], c["vel1"], c["vel2"], c["vel3"], c["Bcc2"], c["Bcc3"], c["press"]])
header = f"""{name}: 1D ideal-MHD reference solution for the GIZMO test of the same name
generated by Athena++ (Stone et al. 2020, ApJS 249, 4), https://github.com/PrincetonUniversity/athena
athena commit: {commit}
configure: python configure.py {configure}
input: test/mhd_reference_athena/athinput.{name}; {scheme}; cfl 0.4
grid: {len(d)} cells on [0, 4], periodic; jump at x = 2 (and its inverted image at x = 0 = 4)
{time_line}
Bx = {Bx[0]:.15g} (constant); B in Athena++ units, magnetic pressure B^2/2 (GIZMO internal MU_0 = 1)
date: {datetime.date.today().isoformat()}
columns: x rho vx vy vz By Bz P"""
np.savetxt(f"{name}_exact.txt", out, fmt="%.8e", header=header)
