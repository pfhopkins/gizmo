#!/usr/bin/env python3
"""Generate chem_net18_tables.h (network 18 rate/cooling data) from an RTZ source tree.
usage: make_net18_tables.py <rtz_dir> <out.h>
<rtz_dir>: `git archive origin/mem_opt` of the RTZ repository (C sources + data/)."""
import os, re, sys

D, OUT = sys.argv[1], sys.argv[2]
NUM = re.compile(r'[-+]?(?:\d+\.\d*|\.\d+|\d+)(?:[eEdD][-+]?\d+)?')


def nums(s):
    return [float(x.replace('d', 'e').replace('D', 'e')) for x in NUM.findall(s)]


def src(f):
    t = open(os.path.join(D, f)).read()
    t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
    return re.sub(r'//[^\n]*', '', t)


def c_array(text, name):
    m = re.search(r'\b' + re.escape(name) + r'\s*(\[[^=]*\])\s*=\s*\{', text)
    if not m:
        sys.exit('array %s not found' % name)
    i, depth = m.end() - 1, 0
    for j in range(i, len(text)):
        depth += text[j] == '{'
        depth -= text[j] == '}'
        if depth == 0:
            body = text[i:j + 1]
            break
    dims = [int(x) for x in re.findall(r'\[(\d+)\]', m.group(1))]
    v = nums(body)
    n = 1
    for d in dims:
        n *= d
    if len(v) != n:
        sys.exit('array %s: %d values, expected %d' % (name, len(v), n))
    return v


def fmt(name, dims, v, ctype='double'):
    n = 1
    for d in dims:
        n *= d
    assert len(v) == n, name
    s = 'static const %s %s%s = {\n' % (ctype, name, ''.join('[%d]' % d for d in dims))
    for k in range(0, n, 6):
        s += '  ' + ', '.join('%.17g' % x for x in v[k:k + 6]) + ',\n'
    return s + '};\n'


def readf(*p):
    return nums(open(os.path.join(D, 'data', *p)).read())


EL = [(1, 'hydrogen', None), (2, 'helium', None), (6, 'carbon', 'CARBON'), (7, 'nitrogen', 'NITROGEN'),
      (8, 'oxygen', 'OXYGEN'), (10, 'neon', 'NEON'), (12, 'magnesium', 'MAGNESIUM'), (14, 'silicon', 'SILICON'),
      (16, 'sulfur', 'SULPHUR'), (26, 'iron', 'IRON')]
out = ['// chem_net18_tables.h -- generated by make_net18_tables.py from RTZ (mem_opt); do not edit.\n',
       '#ifndef CHEM_NET18_TABLES_H\n#define CHEM_NET18_TABLES_H\n']

# radiative recombination (data/rad_rec.dat; recombination.c init_cloudy_rad_rec_data)
t = open(os.path.join(D, 'data', 'rad_rec.dat')).read().split()
rrec = [0.0] * (30 * 30 * 2); rnew = [0.0] * (30 * 30 * 4); fe = [0.0] * (13 * 3)
p = 1
while True:
    i, j = int(t[p]), int(t[p + 1]); p += 2
    if i == -1 and j == -1: break
    for l in range(2): rrec[(i * 30 + j) * 2 + l] = float(t[p + l])
    p += 2
while True:
    i, j = int(t[p]), int(t[p + 1]); p += 2
    if i == -1 and j == -1: break
    for l in range(4): rnew[(i * 30 + j) * 4 + l] = float(t[p + l])
    p += 4
while True:
    i = int(t[p]); p += 1
    if i == -1: break
    for l in range(3): fe[i * 3 + l] = float(t[p + l])
    p += 3
out += [fmt('n18_rrec', [30, 30, 2], rrec), fmt('n18_rnew', [30, 30, 4], rnew), fmt('n18_rfe', [13, 3], fe)]

# dielectronic recombination (recombination.c), rows indexed by ion charge, padded to 27
rc = src('recombination.c')
dr_c, dr_e = [], []
for Z, nm, _ in EL[1:]:
    c = c_array(rc, 'DR_rates_c_' + nm); e = c_array(rc, 'DR_rates_e_' + nm)
    pad = [0.0] * ((27 - (Z + 1)) * 9)
    dr_c += c + pad; dr_e += e + pad
out += [fmt('n18_dr_c', [9, 27, 9], dr_c), fmt('n18_dr_e', [9, 27, 9], dr_e)]

# Voronov collisional ionization (data/collisional_ionization; [Z][n_electrons][5])
v = readf('collisional_ionization', 'collisional_ionization.dat')
ci = [0.0] * (27 * 27 * 5); p = 0
for i in range(1, 27):
    for j in range(i, 0, -1):
        for l in range(5): ci[(i * 27 + j) * 5 + l] = v[p + l]
        p += 5
assert p == len(v)
out.append(fmt('n18_ci', [27, 27, 5], ci))

# charge transfer (charge_transfer.c load_ct_rates)
v = readf('charge_transfer', 'ct_ionization.dat'); cti = [0.0] * (7 * 3 * 31); p = 0
for i in range(3, 31):
    for j in range(3):
        for k in range(7): cti[(k * 3 + j) * 31 + i] = v[p]; p += 1
for j in range(3):
    for k in range(7): cti[(k * 3 + j) * 31 + 2] = 0.0
v = readf('charge_transfer', 'ct_recombination.dat'); ctr = [0.0] * (6 * 4 * 31); p = 0
for i in range(2, 31):
    for j in range(4):
        for k in range(6): ctr[(k * 4 + j) * 31 + i] = v[p]; p += 1
out += [fmt('n18_ction', [7, 3, 31], cti), fmt('n18_ctrec', [6, 4, 31], ctr)]

# cosmic rays (cosmic_ray_ionization.c)
cr = src('cosmic_ray_ionization.c'); crr = []
for Z, nm, _ in EL:
    crr += c_array(cr, 'cosmic_ray_ionization_rates_' + nm)
out.append(fmt('n18_cr', [10, 27], crr))
uv = [0.0] * 27; uvh = [0.0] * 27
for m in re.finditer(r'cosmic_ray_ionization_rates_induced_UV\[(\d+)\]\s*=\s*(' + NUM.pattern + ')', cr):
    uv[int(m.group(1))] = nums(m.group(2))[0]
for m in re.finditer(r'cosmic_ray_ionization_rates_induced_UV_heat\[(\d+)\]\s*=\s*(' + NUM.pattern + ')', cr):
    uvh[int(m.group(1))] = nums(m.group(2))[0]
out += [fmt('n18_cr_uv', [27], uv), fmt('n18_cr_uv_heat', [27], uvh)]

# grain recombination (dust_recombination.c), G0 photoheating (cooling.c)
out.append(fmt('n18_dustrec', [27, 7], c_array(src('dust_recombination.c'), 'dust_rec_coefs')))
co = src('cooling.c')
out.append(fmt('n18_g0_heat', [27], c_array(co, 'G0_heating_rates')))

# high-temperature ion cooling (log10 rates on log10 T grid; [Z+1][121] per element)
out.append(fmt('n18_hit_logT', [121], readf('high_T_cooling', 'temperatures.dat')))
for Z, nm, dd in EL[2:]:
    v = readf('high_T_cooling', dd, 'all_cool.dat')
    out.append(fmt('n18_hit_%d' % Z, [Z + 1, 121], v))

# fine-structure collision tables: [line][160 T][8 colliders] in RTZ file order
fs_names = ["CII_158um", "CI_609um", "CI_230um", "CI_370um", "NII_205um", "NII_76um", "NII_122um", "OI_63um",
            "OI_44um", "OI_145um", "NeII_13um", "SiII_35um", "OIII_88um", "OIII_33um", "OIII_52um", "FeI_14um",
            "FeI_24um", "FeI_35um", "FeII_26um", "FeII_15um", "FeII_35um", "SiI_130um", "SiI_45um", "SiI_68um",
            "SI_17um", "SI_25um", "SI_56um"]
fsv = []
for nmf in fs_names:
    v = readf('fine_structure_data', nmf + '_rates.dat'); assert len(v) == 160 * 8, nmf; fsv += v
out.append(fmt('n18_fs', [27, 160, 8], fsv))

# HM12 UVB photoionization / photoheating per ion ([60 z][Z] per element)
out.append(fmt('n18_uvb_z', [60], readf('HM12', 'redshifts.dat')))
for Z, nm, _ in EL:
    for k in ('pi', 'ph'):
        v = readf('HM12', '%s_%s.dat' % (nm, k)); assert len(v) == 60 * Z, nm
        out.append(fmt('n18_uvb_%s_%d' % (k, Z), [60, Z], v))

out.append('#endif\n')
open(OUT, 'w').write(''.join(out))
print('wrote', OUT, os.path.getsize(OUT), 'bytes')
