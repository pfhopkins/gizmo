"""Build the net-20 CIE tables: He and metal cooling (per nH^2, at CIE x_e) and
CIE electron abundances of He and metals, from the published CIE ion fractions
and ion-by-ion cooling efficiencies (GF12 data files), with protosolar abundances
for H, He, C, N, O, Ne, Mg, Si, S, Fe.  Writes a C header.

usage: python3 -I make_cie_table.py <datadir> <out.h>
"""
import sys, os
import numpy as np

ddir, out = sys.argv[1], sys.argv[2]

# element: (data file name, Z, abundance per H)
ELEM = [("H", "Hydrogen", 1, 1.0), ("He", "Helium", 2, 9.55e-2),
        ("C", "Carbon", 6, 2.95e-4), ("N", "Nitrogen", 7, 7.41e-5),
        ("O", "Oxygen", 8, 5.37e-4), ("Ne", "Neon", 10, 9.33e-5),
        ("Mg", "Magnesium", 12, 4.37e-5), ("Si", "Silicon", 14, 3.55e-5),
        ("S", "Sulfur", 16, 1.45e-5), ("Fe", "Iron", 26, 3.47e-5)]

# --- CIE ion fractions: columns T, then ion stages in element order ---
rows = []
with open(os.path.join(ddir, "Gnat_Sternberg07_cie_ion_frac.txt")) as f:
    lines = f.readlines()
ncol = 1 + sum(z + 1 for _, _, z, _ in ELEM)
for l in lines[125:]:
    sp = l.split()
    if len(sp) == ncol:
        rows.append([float(v) for v in sp])
fr = np.array(rows)
T = fr[:, 0]
assert np.all(np.diff(T) > 0) and T[0] == 1e4, (T[0], T[-1])
frac = {}
k = 1
for e, _, z, _ in ELEM:
    frac[e] = fr[:, k:k + z + 1]
    k += z + 1
assert k == ncol

# --- ion-by-ion cooling efficiencies, interpolated to the GS07 grid ---
def read_cool(name, z):
    with open(os.path.join(ddir, "tables", name + ".txt")) as f:
        ls = f.readlines()[(z + 1) + 12:]
    a = np.array([[float(v) for v in l.split()] for l in ls if l.strip()])
    out = np.empty((len(T), z + 1))
    for i in range(z + 1):
        out[:, i] = np.interp(T, a[:, 0], a[:, i + 1])
    return out

xe = {}
for e, name, z, A in ELEM:
    xe[e] = A * (frac[e] * np.arange(z + 1)[None, :]).sum(axis=1)
xe_tot = sum(xe.values())
cool = {}
for e, name, z, A in ELEM:
    cool[e] = xe_tot * A * (frac[e] * read_cool(name, z)).sum(axis=1)

lam_he = cool["He"]
lam_met = sum(cool[e] for e, _, _, _ in ELEM if e not in ("H", "He"))
xe_he = xe["He"]
xe_met = sum(xe[e] for e, _, _, _ in ELEM if e not in ("H", "He"))

def arr(name, v, fmt):
    s = "static const double %s[CHEM20_NCIE] = {\n" % name
    for i in range(0, len(v), 6):
        s += "    " + ", ".join(fmt % x for x in v[i:i + 6]) + ",\n"
    return s + "};\n"

floor = 1e-300
with open(out, "w") as f:
    f.write("// chem_net20_cie.h -- generated by make_cie_table.py; do not edit.\n")
    f.write("// CIE He/metal cooling [erg cm^3 s^-1 per nH^2 at CIE x_e] and CIE electrons per H,\n")
    f.write("// protosolar abundances (H He C N O Ne Mg Si S Fe), metals for Z'=1.\n")
    f.write("#ifndef CHEM_NET20_CIE_H\n#define CHEM_NET20_CIE_H\n")
    f.write("#define CHEM20_NCIE %d\n" % len(T))
    f.write(arr("chem20_cie_log10T", np.log10(T), "%.6f"))
    f.write(arr("chem20_cie_log10_lam_he", np.log10(np.maximum(lam_he, floor)), "%.6f"))
    f.write(arr("chem20_cie_log10_lam_met", np.log10(np.maximum(lam_met, floor)), "%.6f"))
    f.write(arr("chem20_cie_xe_he", xe_he, "%.6e"))
    f.write(arr("chem20_cie_xe_met", xe_met, "%.6e"))
    f.write("#endif\n")

i = np.argmax(lam_he + lam_met)
print("grid: %d points, T = %.3g .. %.3g K" % (len(T), T[0], T[-1]))
print("peak Lambda_He+metal = %.3e at T = %.3g K (paper: total peak 5.5e-22 at a few 1e5 K)" %
      ((lam_he + lam_met)[i], T[i]))
for t in (2e4, 3.5e4, 1e5, 3e5, 1e6, 1e7):
    j = np.argmin(abs(T - t))
    print("T=%.3g  lamHe=%.3e lamMet=%.3e  xeHe=%.3e xeMet=%.3e xeH=%.3e" %
          (T[j], lam_he[j], lam_met[j], xe_he[j], xe_met[j], xe["H"][j]))
