#!/bin/bash
# Converged references (Uli 2026-11-19: gates compare each backend against the converged solution, 1% bar):
# both backends at rtol 1e-8 (C++ CHEM_RTOL, Fortran RTOL). Writes, into OUT:
#   net<N>_converged_reference.txt          test_solver_failure.cc phases A and H (build_solver_failure.sh REFERENCE=1)
#   net<N>_onezone_converged_reference.txt  test_conservation.cc phase-M one-zone (build_conservation.sh REFERENCE=1)
# Commit them to cooling/sgchem/cxx/golden/.
#
# usage: make_converged_references.sh TREE CONFIG OUT COMMIT
#   TREE    a COPY of the gizmo tree at COMMIT, net 5 or 17 GIZMO_config.h from CONFIG at its root, SGChem tables in place
#   CONFIG  the Config.sh of TREE (build_conservation.sh regenerates the config from it); the committed ones are
#           golden/net5_wlm_Config.sh and golden/net17_wlm_Config.sh (the WLM n5/n17 runs of 2026-11-16)
#   COMMIT  the commit TREE was taken from (named in the headers)
# Run inside a batch job (never on the login node).
set -e
TREE=$(readlink -f "$1"); CONFIG=$(readlink -f "$2"); OUT=$(readlink -f -m "$3"); COMMIT=$4
G=$(dirname "$(readlink -f "$0")")
NET=$(sed -n 's/^#define CHEMISTRYNETWORK \([0-9]*\).*/\1/p' "$TREE/GIZMO_config.h")
mkdir -p "$OUT"
REFERENCE=1 JOBS=${JOBS:-2} bash "$G/build_solver_failure.sh" "$TREE" "$OUT/ah_build"
REFERENCE=1 JOBS=${JOBS:-2} CANON_CONFIG="$CONFIG" bash "$G/build_conservation.sh" "$TREE" "$OUT/onezone_build" "$NET"
SUN=${SUNDIALS_DIR:-/orion/ptmp/uli/orion/fb_tests/_sundials/install}
SUNV=$(sed -n 's/^#define SUNDIALS_VERSION "\(.*\)"/\1/p' "$SUN/include/sundials/sundials_config.h")
TMD5=$(cd "$TREE/cooling/sgchem" && md5sum eh2-table.txt energy-table-x.txt H2-cooling-ratios.dat wss_z_collis.txt | awk '{printf "%s %s; ", $2, $1}')
HDR="# generated by cooling/sgchem/cxx/golden/make_converged_references.sh at commit $COMMIT, net $NET ($(date +%F)); both backends at rtol 1e-8
# config $(basename "$CONFIG") md5 $(md5sum < "$CONFIG" | cut -c1-32); tables: $TMD5; SUNDIALS $SUNV"
{ echo "$HDR"; echo "# test_solver_failure.cc phases A and H in call order: tag id dt nH T_C T_F"
  cat "$OUT/ah_build/default/AH.csv"; } > "$OUT/net${NET}_converged_reference.txt"
{ echo "$HDR"; echo "# test_conservation.cc phase-M one-zone (n 4.4, T0 1.65e5 K, dt 1.017e11 s): Gamma_HI T_C T_F x_H+_C x_H+_F"
  cat "$OUT/onezone_build/onezone_reference_net$NET.txt"; } > "$OUT/net${NET}_onezone_converged_reference.txt"
awk '!/^#/ { r = ($5 - $6) / $5; if (r < 0) r = -r; if (r > m) m = r; n++ } END { printf "net %s A/H reference: %d calls, worst |T_C - T_F|/T_C %.3g\n", "'"$NET"'", n, m }' "$OUT/net${NET}_converged_reference.txt"
awk '!/^#/ { r = ($2 - $3) / $2; if (r < 0) r = -r; if (r > m) m = r; n++ } END { printf "net %s one-zone reference: %d lines, worst |T_C - T_F|/T_C %.3g\n", "'"$NET"'", n, m }' "$OUT/net${NET}_onezone_converged_reference.txt"
